// Visual check of a late-game capital, night, battles. Run with the test server on :8123.
const { chromium, devices } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('console', m => { if (m.type() === 'error') errs.push(m.type() + ': ' + m.text()); });
  p.on('pageerror', e => errs.push('PAGEERR ' + e.message + '\n' + e.stack));
  await p.goto('http://localhost:8123/');
  await p.waitForTimeout(1200);
  await p.click('#m-start');
  const dir = process.env.SHOTS || '/tmp/claude-0/shots';
  const shot = async (n) => { await p.waitForTimeout(500); await p.screenshot({ path: `${dir}/${n}.png` }); };
  await p.evaluate(() => {
    const { G } = window.__game;
    const s = G.s;
    s.level = 36; s.gold = 1e22; s.ore = 1e7; s.mushrooms = 1e9; s.gems = 5000;
    for (const d of ['market', 'shady', 'hoard', 'dragon']) s.districts[d] = true;
    const lv = { shroom: 420, mine: 260, tavern: 150, smithy: 120, potion: 101, market: 60, casino: 55, thieves: 30, bank: 25, arena: 12, alchemy: 10, hatchery: 5, palace: 1 };
    for (const k in lv) s.buildings[k].lvl = lv[k];
    for (const k of ['lodge', 'research', 'barracks', 'tower']) s.buildings[k].lvl = 3;
    s.buildings.huts.lvl = 12; s.buildings.cauldron.lvl = 5;
    for (let i = 0; i < 18; i++) G.addRecruit([0, 1, 2, 3, 4][i % 5], 'test');
    for (const b of ['shroom', 'mine', 'tavern', 'smithy', 'potion', 'market', 'casino', 'thieves', 'bank']) G.autoAssign(b);
    window.__game.world.terrainDirty = true;
  });
  await p.waitForTimeout(1500);
  await p.evaluate(() => { const ui = window.__game.ui; ui.modalQueue = []; ui.closeModal(); ui.modalQueue = []; ui.closeModal(); });
  await p.evaluate(() => { const w = window.__game.world; w.cam.zoom = 1.1; w.cam.x = 28 * 16; w.cam.y = 18 * 16; w.clampCam(); });
  await shot('10-overview');
  await p.evaluate(() => { const w = window.__game.world; w.cam.zoom = 2; w.cam.x = 32 * 16; w.cam.y = 20 * 16; w.clampCam(); });
  await shot('11-center');
  await p.evaluate(() => { const w = window.__game.world; w.cam.x = 26 * 16; w.cam.y = 8 * 16; w.clampCam(); });
  await shot('12-dragon');
  await p.evaluate(() => { const w = window.__game.world; w.cam.x = 8 * 16; w.cam.y = 14 * 16; w.clampCam(); });
  await shot('13-shady');
  await p.evaluate(() => { const w = window.__game.world; w.time = w.dayLen * 0.62; w.cam.x = 30 * 16; w.cam.y = 21 * 16; });
  await shot('14-night');
  await p.evaluate(() => { const w = window.__game.world; w.time = 1; });
  await p.click('#nav button[data-tab=explore]');
  await shot('15-explore');
  await p.click('[data-act=region][data-id=woods]');
  await shot('16-region');
  await p.evaluate(() => window.__game.ui.startBattle('woods', 9));
  await p.waitForTimeout(1500);
  await shot('17-battle');
  for (let i = 0; i < 8; i++) await p.mouse.click(300, 400);
  await p.evaluate(() => { window.__game.battle.bombCharge = 1; });
  await p.click('#bt-bomb');
  await p.waitForTimeout(500);
  await shot('18-bomb');
  await p.waitForTimeout(12000);
  await shot('19-battle-end');
  console.log(errs.join('\n') || 'no errors');
  await b.close();
})();
